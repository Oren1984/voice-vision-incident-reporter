"""Render docs/experiment-results.md from results/*.json so every number in it comes from a results file.

Usage: python tools/render_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
LABELS = ["affected_individuals", "infrastructure_and_utility_damage", "not_humanitarian", "other_relevant_information",
          "rescue_volunteering_or_donation_effort"]
SHORT = ["affected", "infrastructure", "not_hum.", "other_rel.", "rescue"]


def load(name):
    p = R / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, d=3):
    return "—" if x is None else f"{x:.{d}f}"


def pct(x, d=1):
    return "—" if x is None else f"{100 * x:.{d}f}%"


def ci(b):
    return f"{b['point']:+.3f} [{b['ci95'][0]:+.3f}, {b['ci95'][1]:+.3f}]"


def cm_table(cm):
    lines = ["| true ↓ / predicted → | " + " | ".join(SHORT) + " |", "|---|" + "---:|" * 5]
    for lab, row in zip(SHORT, cm):
        lines.append(f"| **{lab}** | " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def main() -> None:
    dc, sel, rq = load("data_checks.json"), load("rq1_selection.json"), load("rq1_results.json")
    s3, ex, obs = load("s3_diffattn_results.json"), load("exploratory.json"), load("observation_check.json")
    sp1, sp2, sp3, man = load("speech_librispeech.json"), load("speech_scripted.json"), load("speech_sp3.json"), load("run_manifest.json")
    res = rq["results"]
    out = []
    w = out.append
    w("# Experiment results\n")
    w("_Generated by `python tools/render_results.py` from `results/*.json`. Protocol: [experiment-design.md](experiment-design.md) (v1, frozen before any run). Do not edit numbers by hand._\n")

    h1 = rq["h1"]
    w("## Answer to the research question\n")
    w(f"> **RQ1 — does text + image beat the best single source on the same examples?** "
      f"**Not reliably.** On the {rq['test_n']} official test pairs, the combined model reaches Macro F1 "
      f"**{f(res['combined']['macro_f1'])}**, image only **{f(res['image']['macro_f1'])}**, text only **{f(res['text']['macro_f1'])}**. "
      f"The gain over the best single source (image) is {h1['point']:+.3f} with a 95% paired-bootstrap CI of "
      f"[{h1['ci95'][0]:+.3f}, {h1['ci95'][1]:+.3f}], which includes 0 — the pre-registered success criterion is **not met** "
      f"(verdict: *{h1['verdict']}*). Combining **does** reliably beat text alone "
      f"({ci(rq['bootstrap']['combined_minus_text'])}).\n")
    w("What this means for the application: the combined view is at least as good as either source and clearly better than "
      "the text alone, so it is used for the category *proposal* — but it is not strong enough to overrule a person, and "
      f"when the text-only and image-only views disagree ({rq['view_agreement']['views_disagree']} of {rq['test_n']} test pairs) "
      f"the combined view is right only {pct(rq['view_agreement']['accuracy_when_views_disagree'])} of the time "
      f"(vs {pct(rq['view_agreement']['accuracy_when_views_agree'])} when they agree). That is why disagreement is surfaced to the reviewer.\n")

    w("## Data\n")
    t = dc["splits"]["test"]["class_counts"]
    w(f"CrisisMMD v2.0, official agreed-label humanitarian split. Train {dc['splits']['train']['rows']:,} / dev {dc['splits']['dev']['rows']:,} / "
      f"test {dc['splits']['test']['rows']:,} pairs; no missing or unreadable images ({dc['missing_images']} / {dc['unreadable_images']}). "
      f"Test class counts: " + ", ".join(f"{s} {t[l]}" for s, l in zip(SHORT, LABELS)) + ".\n")
    lk = dc["leakage_vs_train"]["test"]
    w(f"Leakage checks (test vs train): tweet-id overlap {lk['tweet_id_overlap']}, image-path overlap {lk['image_path_overlap']}, "
      f"normalised-text duplicates {lk['normalised_text_duplicates_of_train']}, near-duplicate images {lk['near_duplicate_images_of_train_ahash_le4']} "
      f"(average hash, Hamming ≤ 4). Details: [dataset.md](dataset.md).\n")

    w("## Model selection (dev only)\n")
    w("| View | selected C | class weight | dev Macro F1 |\n|---|---:|---|---:|")
    for v in ("text", "image", "combined"):
        s = sel["views"][v]["selected"]
        w(f"| {v} | {s['C']} | {s['class_weight']} | {f(s['dev_macro_f1'])} |")
    w(f"\nLate fusion (S1): w_text = {sel['late_fusion']['selected_w_text']} (dev Macro F1 {f(sel['late_fusion']['dev_macro_f1'])}). "
      "The combined model's C = 100 is at the upper edge of the pre-registered grid; the grid was not widened after the fact.\n")

    w(f"## Test results (n = {rq['test_n']}, scored once)\n")
    w("| Model | Macro F1 | Accuracy | Weighted F1 | ECE (15 bins) |\n|---|---:|---:|---:|---:|")
    names = [("text", "Text only (LR)"), ("image", "Image only (LR)"), ("combined", "**Combined, early fusion (LR) — primary**"),
             ("late_fusion", "S1 late fusion"), ("zero_shot_text", "S2 zero-shot text"), ("zero_shot_image", "S2 zero-shot image"),
             ("zero_shot_combined", "S2 zero-shot combined (app fallback)")]
    for k, n in names:
        r = res[k]
        w(f"| {n} | {f(r['macro_f1'])} | {f(r['accuracy'])} | {f(r['weighted_f1'])} | {f(r['ece_15'])} |")
    if s3:
        w(f"| S3 guided gating + differential attention (ours), mean ± sd of 3 seeds | {f(s3['test_macro_f1_mean'])} ± {f(s3['test_macro_f1_sd'])} | "
          f"{f(s3['test_accuracy_mean'])} | — | — |")
    w("\n### Paired bootstrap (10,000 resamples of the test set, seed 2026)\n")
    w("| Difference in Macro F1 | point [95% CI] | resamples > 0 |\n|---|---|---:|")
    for k, n in (("combined_minus_best_unimodal", "combined − max(text, image) **(H1)**"), ("combined_minus_image", "combined − image"),
                 ("combined_minus_text", "combined − text"), ("late_fusion_minus_best_unimodal", "late fusion − max(text, image)")):
        b = rq["bootstrap"][k]
        w(f"| {n} | {ci(b)} | {pct(b['share_resamples_above_0'])} |")
    m = rq["mcnemar_combined_vs_best_unimodal"]
    w(f"\nExact McNemar test, combined vs image on correctness: combined right / image wrong **{m['a_right_b_wrong']}**, "
      f"combined wrong / image right **{m['a_wrong_b_right']}**, p = {m['p_value_two_sided']:.3f}. In accuracy the two are practically tied.\n")

    w("### Per-class F1 (test support in brackets)\n")
    sup = res["text"]["per_class"]["support"]
    w("| View | " + " | ".join(f"{s} [{n}]" for s, n in zip(SHORT, sup)) + " |\n|---|" + "---:|" * 5)
    for v in ("text", "image", "combined"):
        w(f"| {v} | " + " | ".join(f(x) for x in res[v]["per_class"]["f1"]) + " |")
    w("\n`affected_individuals` has 9 test examples: one example moves its F1 by several points, and it weighs one fifth in Macro F1.\n")
    w("### Confusion matrices\n")
    for v in ("text", "image", "combined"):
        w(f"**{v}**\n\n" + cm_table(res[v]["confusion_matrix"]) + "\n")

    sens = rq["sensitivity_no_near_duplicates"]
    w("### Sensitivity: without near-duplicates of training data\n")
    w(f"Excluding {sens['excluded']} test pairs whose image is a near-duplicate of a training image or whose text duplicates a training "
      f"tweet (n = {sens['n']}): text {f(sens['text'])}, image {f(sens['image'])}, combined {f(sens['combined'])} Macro F1; combined − best single "
      f"source {sens['combined_minus_best_unimodal']:+.3f}. The conclusion does not change.\n")

    w("### By disaster event (Macro F1)\n")
    w("| Event | n | text | image | combined |\n|---|---:|---:|---:|---:|")
    for e, r in rq["by_event"].items():
        w(f"| {e} | {r['n']} | {f(r['text'])} | {f(r['image'])} | {f(r['combined'])} |")
    w("\nSmall per-event samples; shown for transparency, not for conclusions.\n")

    va = rq["view_agreement"]
    w("### How the single-source views relate\n")
    w(f"| | count |\n|---|---:|\n| both right | {va['text_right_image_right']} |\n| text right, image wrong | {va['text_right_image_wrong']} |\n"
      f"| text wrong, image right | {va['text_wrong_image_right']} |\n| both wrong | {va['both_wrong']} |\n")
    w(f"Text and image are complementary on {va['text_right_image_wrong'] + va['text_wrong_image_right']} pairs, but a linear combination "
      "recovers only part of that. Combined accuracy when the two views agree / disagree: "
      f"{pct(va['accuracy_when_views_agree'])} / {pct(va['accuracy_when_views_disagree'])}.\n")

    if s3:
        b = s3["bootstrap"]
        w("## S3 — paper-inspired fusion head\n")
        w(f"{s3['model']}; {s3['params']:,} parameters. Test Macro F1 per seed: "
          + ", ".join(f"{r['seed']}: {f(r['test']['macro_f1'])} ({r['epochs']} epochs)" for r in s3["runs"])
          + f". Mean {f(s3['test_macro_f1_mean'])} ± {f(s3['test_macro_f1_sd'])}, i.e. {s3['mean_minus_primary_combined']:+.3f} vs the primary combined model. "
          f"Additionally computed (not pre-registered): the 3-seed probability ensemble reaches {f(s3['s3_seed_ensemble_macro_f1'])}; vs best single source "
          f"{ci(b['s3_ensemble_minus_best_unimodal'])}, vs primary combined {ci(b['s3_ensemble_minus_primary_combined'])} — neither CI excludes 0. "
          "The attention-based head does not change the answer to RQ1 in this setting.\n")

    if ex:
        a, bb = ex["a_macro_f1_4_classes_without_affected_individuals"], ex["b_all_views_balanced_class_weights"]
        w("## Post-hoc exploratory checks (not pre-registered)\n")
        w("Added after seeing the results, because the combined model's advantage rests partly on the 9-example class and because dev "
          "selection gave only the combined model balanced class weights.\n")
        w(f"- **Without `affected_individuals` (4-class Macro F1):** text {f(a['text'])}, image {f(a['image'])}, combined {f(a['combined'])} → "
          f"combined − best {a['combined_minus_best_unimodal']:+.3f}. Most of the gap over image comes from the tiny class.\n"
          f"- **All views with balanced class weights** (C re-selected on dev: {bb['selected_C_on_dev']}): text {f(bb['test_macro_f1']['text'])}, "
          f"image {f(bb['test_macro_f1']['image'])}, combined {f(bb['test_macro_f1']['combined'])}; combined − best {ci(bb['combined_minus_best_unimodal'])}. "
          "The margin widens because balanced weighting hurts the single-source models, not because the combined model improves.\n")
        w("Reading: fusion's benefit over the image alone is small and sensitive to class weighting and to a handful of rare-class examples.\n")

    if obs:
        w("## Image observation sanity check (CrisisMMD dev)\n")
        w(obs["note"] + "\n")
        w("| Concept | related class | AUROC | share 'likely' | share 'possible' |\n|---|---|---:|---:|---:|")
        for cid, r in obs["concepts"].items():
            w(f"| {cid} | {r.get('related_class', '—')} | {f(r.get('auroc'))} | {pct(r['likely_share'])} | {pct(r['possible_share'])} |")
        w("\nConcept scores rank related images above others (AUROC 0.64–0.90), i.e. they carry signal but are far from reliable; "
          "the app shows them as scores with bands, never as facts.\n")

    w("## Speech workflow (our extension — not a paper result)\n")
    if sp1:
        w(f"### SP1 — real read speech (LibriSpeech test-clean)\n")
        w(f"{sp1['sample']['n']} utterances ({sp1['sample']['speakers']} speakers, {sp1['sample']['hours']} h, seed {sp1['sample']['seed']}): "
          f"**WER {pct(sp1['wer'])}**, CER {pct(sp1['cer'])}; {sp1['utterances_with_zero_errors']} utterances without any error. "
          "Audiobook speech, not incident reports; it grounds the recogniser's accuracy on real voices.\n")
    else:
        w("### SP1 — pending\n")
    if sp2:
        w("### SP2 — scripted incident reports, synthetic voices, added noise\n")
        w(f"{len(sp2['clips']) // 3} clips (24 project-authored reports × 4 Kokoro voices), each transcribed clean, at 10 dB and at 0 dB SNR.\n")
        w("| Condition | WER | CER | critical-term recall | concept-set F1 | clips with changed concepts | clips with changed missing-info questions | text-view category flips |\n|---|---:|---:|---:|---:|---:|---:|---:|")
        for c, s in sp2["summary"].items():
            w(f"| {c} | {pct(s['wer'])} | {pct(s['cer'])} | {pct(s['critical_term_recall'])} | {f(s['concept_set_f1_mean'])} | "
              f"{s['clips_with_changed_concepts']} / {s['clips']} | {s['clips_with_changed_missing_fields']} / {s['clips']} | {s['text_view_category_flips']} / {s['clips']} |")
        w("\n**Examples where a transcription error changed the downstream result** (reference → recognised):\n")
        shown = 0
        for c in sp2["clips"]:
            changed = c["concepts_ref"] != c["concepts_hyp"] or c["missing_ref"] != c["missing_hyp"] or c["text_view_ref"] != c["text_view_hyp"]
            if changed and c["condition"] != "clean" and shown < 6:
                what = []
                if c["concepts_ref"] != c["concepts_hyp"]:
                    what.append(f"concepts {c['concepts_ref']} → {c['concepts_hyp']}")
                if c["missing_ref"] != c["missing_hyp"]:
                    what.append(f"missing-info {c['missing_ref']} → {c['missing_hyp']}")
                if c["text_view_ref"] != c["text_view_hyp"]:
                    what.append(f"text-view category {c['text_view_ref']} → {c['text_view_hyp']}")
                w(f"- `{c['id']}` {c['voice']}, {c['condition']}: “{c['reference']}” → “{c['hypothesis']}” — " + "; ".join(what))
                shown += 1
        clean = [c for c in sp2["clips"] if c["condition"] == "clean" and (c["concepts_ref"] != c["concepts_hyp"] or c["missing_ref"] != c["missing_hyp"])]
        for c in clean[:2]:
            w(f"- `{c['id']}` {c['voice']}, clean: “{c['reference']}” → “{c['hypothesis']}” — concepts {c['concepts_ref']} → {c['concepts_hyp']}; missing {c['missing_ref']} → {c['missing_hyp']}")
        w("\nSynthetic TTS speech is cleaner and more regular than a caller on a phone; these numbers are an optimistic bound.\n")
    else:
        w("### SP2 — pending\n")
    if sp3:
        rr = sp3["results"]
        w("### SP3 — cost of a voice channel on the RQ1 test set\n")
        w(f"The {sp3['n']} test tweets read aloud by Kokoro ({sp3['audio_hours']} h of synthetic speech), transcribed, and classified by the frozen RQ1 heads "
          f"(no retraining). WER clean {pct(sp3['wer_clean'])}, at 10 dB SNR {pct(sp3['wer_snr10'])}.\n")
        w("| Text given to the model | text-only Macro F1 | combined Macro F1 | text-only predictions changed vs original | combined predictions changed |\n|---|---:|---:|---:|---:|")
        for k, n in (("original_text", "original tweet (RQ1 input)"), ("speakable_reference", "spoken form (hashtags as words, no mentions/URLs)"),
                     ("asr_clean", "ASR transcript, clean synthetic speech"), ("asr_snr10", "ASR transcript, 10 dB SNR")):
            r = rr[k]
            w(f"| {n} | {f(r['text_only_macro_f1'])} | {f(r['combined_macro_f1'])} | {r.get('text_only_prediction_changes_vs_original', '—')} | {r.get('combined_prediction_changes_vs_original', '—')} |")
        w(f"\nText-only drop from original text to clean-speech transcript: {sp3['text_only_drop_original_to_asr_clean']:+.3f} "
          f"(pre-stated 'robust' bound: ≤ 0.03); combined: {sp3['combined_drop_original_to_asr_clean']:+.3f}. "
          "Synthetic speech of written posts — not real voice reports.\n")
    else:
        w("### SP3 — pending\n")

    w("## Reproduce\n")
    w("```powershell\n$env:VVIR_OFFLINE = \"1\"   # after the first model download; set VVIR_USE_OS_TRUSTSTORE=1 for the download behind TLS inspection\n"
      "python -m experiments.prepare            # needs .cache/crisismmd/ (see dataset.md)\npython -m experiments.extract_features\n"
      "python -m experiments.run_rq1 select\npython -m experiments.run_rq1 test\npython -m experiments.run_s3_diffattn\n"
      "python -m experiments.observation_check\npython -m experiments.exploratory      # post hoc\n"
      "python -m experiments.speech_eval scripted\npython -m experiments.speech_eval librispeech\npython -m experiments.speech_eval sp3\n"
      "python tools/render_results.py\n```\n")
    if man:
        env = man["environment"]
        w(f"Environment of the recorded run: Python {env['python']}, {env['platform']}; " + ", ".join(f"{k} {v}" for k, v in env["packages"].items())
          + f". CLIP revision `{man['clip']['revision']}`; seeds: model {man['rq1']['seed']}, bootstrap {man['rq1']['bootstrap_seed']}, S3 13/42/7. CPU only.\n")
    w("## Deviations from the protocol\n")
    w("- None for RQ1. S3's seed ensemble and the two exploratory checks above are additional, clearly labelled analyses.\n"
      "- The application's image-observation scoring was changed from a background-softmax to a margin score after it proved overconfident on the demo "
      "photos (see [architecture.md](architecture.md)); this affects the app's observations only, not any RQ1 model.\n")
    (ROOT / "docs" / "experiment-results.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/experiment-results.md")


if __name__ == "__main__":
    main()
